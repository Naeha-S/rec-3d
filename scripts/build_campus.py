# Coordinate mapping: WebGL (x=East, y=Up, -z=North) -> Blender (X=East, Y=North, Z=Up)
def to_bl(wx: float, wy_up: float, wz: float) -> tuple[float, float, float]:
    return (float(wx), float(-wz), float(wy_up))


def sample_elev(elev: dict, wx: float, wz: float) -> float:
    cell = elev["cell"]
    grid = elev["grid"]
    rows, cols = len(grid), len(grid[0])
    half_w = (cols - 1) * cell * 0.5
    half_d = (rows - 1) * cell * 0.5
    u = max(0.0, min(cols - 1.001, (wx + half_w) / cell))
    v = max(0.0, min(rows - 1.001, (wz + half_d) / cell))
    ic, ir = int(u), int(v)
    du, dv = u - ic, v - ir
    return (
        (1 - du) * (1 - dv) * grid[ir][ic]
        + du * (1 - dv) * grid[ir][ic + 1]
        + (1 - du) * dv * grid[ir + 1][ic]
        + du * dv * grid[ir + 1][ic + 1]
    )


def hex_to_rgba(hex_str: str, alpha: float = 1.0) -> tuple[float, float, float, float]:
    h = hex_str.lstrip("#")
    srgb = [int(h[i : i + 2], 16) / 255.0 for i in (0, 2, 4)]
    # Convert sRGB to linear RGB for accurate Blender PBR colors
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in srgb]
    return (lin[0], lin[1], lin[2], alpha)


MAT_CACHE: dict[str, bpy.types.Material] = {}


def get_mat(
    name: str,
    hex_color: str,
    roughness: float = 0.85,
    metallic: float = 0.0,
    emission_hex: str | None = None,
    emission_strength: float = 0.0,
    alpha: float = 1.0,
) -> bpy.types.Material:
    if name in MAT_CACHE:
        return MAT_CACHE[name]
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs["Base Color"].default_value = hex_to_rgba(hex_color, alpha)
        bsdf.inputs["Roughness"].default_value = roughness
        bsdf.inputs["Metallic"].default_value = metallic
        if alpha < 1.0:
            if "Alpha" in bsdf.inputs:
                bsdf.inputs["Alpha"].default_value = alpha
            if hasattr(mat, "blend_method"):
                mat.blend_method = "BLEND"
        if emission_hex and emission_strength > 0:
            em_col = hex_to_rgba(emission_hex, 1.0)
            if "Emission Color" in bsdf.inputs:
                bsdf.inputs["Emission Color"].default_value = em_col
            elif "Emission" in bsdf.inputs:
                bsdf.inputs["Emission"].default_value = em_col
            if "Emission Strength" in bsdf.inputs:
                bsdf.inputs["Emission Strength"].default_value = emission_strength
    MAT_CACHE[name] = mat
    return mat


def make_collection(name: str, parent: bpy.types.Collection) -> bpy.types.Collection:
    col = bpy.data.collections.new(name)
    parent.children.link(col)
    return col


def link_obj(obj: bpy.types.Object, col: bpy.types.Collection) -> bpy.types.Object:
    col.objects.link(obj)
    return obj


def add_box(
    name: str,
    size_xyz: tuple[float, float, float],
    loc_xyz: tuple[float, float, float],
    rot_z: float,
    mat: bpy.types.Material,
    col: bpy.types.Collection,
    rot_euler: tuple[float, float, float] | None = None,
) -> bpy.types.Object:
    mesh = bpy.data.meshes.new(name + "_m")
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    bmesh.ops.scale(bm, vec=size_xyz, verts=bm.verts)
    bm.to_mesh(mesh)
    bm.free()
    mesh.materials.append(mat)
    obj = bpy.data.objects.new(name, mesh)
    obj.location = loc_xyz
    if rot_euler is not None:
        obj.rotation_euler = rot_euler
    else:
        obj.rotation_euler = (0.0, 0.0, rot_z)
    return link_obj(obj, col)


def add_cyl(
    name: str,
    r_bottom: float,
    r_top: float,
    depth: float,
    segs: int,
    loc_xyz: tuple[float, float, float],
    mat: bpy.types.Material,
    col: bpy.types.Collection,
    rot_euler: tuple[float, float, float] = (0.0, 0.0, 0.0),
) -> bpy.types.Object:
    mesh = bpy.data.meshes.new(name + "_m")
    bm = bmesh.new()
    bmesh.ops.create_cone(
        bm,
        cap_ends=True,
        cap_tris=False,
        segments=segs,
        radius1=r_bottom,
        radius2=r_top,
        depth=depth,
    )
    bm.to_mesh(mesh)
    bm.free()
    mesh.materials.append(mat)
    obj = bpy.data.objects.new(name, mesh)
    obj.location = loc_xyz
    obj.rotation_euler = rot_euler
    return link_obj(obj, col)


def polygon_centroid(poly: list[list[float]]) -> tuple[float, float]:
    n = len(poly)
    return (sum(p[0] for p in poly) / n, sum(p[1] for p in poly) / n)


def principal_obb(poly: list[list[float]]):
    best_len = 0.0
    ux, uz = 1.0, 0.0
    for i in range(len(poly)):
        x1, z1 = poly[i]
        x2, z2 = poly[(i + 1) % len(poly)]
        ln = math.hypot(x2 - x1, z2 - z1)
        if ln > best_len:
            best_len = ln
            ux, uz = (x2 - x1) / ln, (z2 - z1) / ln
    vx, vz = -uz, ux
    cx, cz = polygon_centroid(poly)
    us = [(p[0] - cx) * ux + (p[1] - cz) * uz for p in poly]
    vs = [(p[0] - cx) * vx + (p[1] - cz) * vz for p in poly]
    # Blender Z-rotation of vector (ux, -uz)
    bl_rot_z = math.atan2(-uz, ux)
    return cx, cz, ux, uz, vx, vz, min(us), max(us), min(vs), max(vs), bl_rot_z


